"""Reproduce the README example with the real engine and disposable data only."""
import argparse
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine import RULES_VERSION, calculate_round, regional_shock
from store import Store

# A public example seed, never copied from a real classroom.
EXAMPLE_SEED = 'insgame2026-readme-demo-v1'
SNAPSHOT = ROOT / 'docs' / 'EXAMPLE_RESULTS.md'


def render_example():
    with tempfile.TemporaryDirectory(prefix='insgame-example-') as directory:
        game = Store(Path(directory) / 'example.sqlite3').create(
            dict(name='README example', teams=5, total_rounds=5, demo=True))
        results = calculate_round(game['env'], game['teams'], game['decisions'], 1,
                                  game['total_rounds'], game['market']['policies'], EXAMPLE_SEED)
    lines = [
        '# Reproducible example: one round, five demo teams', '',
        f'Rules version: **{RULES_VERSION}**. Generated by `python examples/demo_round.py`.', '',
        'This uses the real calculation engine and the same starting decisions as the browser\'s ',
        '**Create demo** button. A public example seed fixes the regional shocks so the table ',
        'can be reproduced. A newly created browser classroom has its own private seed and ',
        'will not necessarily produce these results. All amounts are currency units (CU).', '',
        f"Round 1 of 5; weight **{game['round_weights'][0]:.6%}**. "
        f"Low-risk shock **{regional_shock(EXAMPLE_SEED, 1, 'low'):.1f}x**; "
        f"high-risk shock **{regional_shock(EXAMPLE_SEED, 1, 'high'):.1f}x**.", '',
        '## Starting decisions', '',
        '| Team | Low premium | High premium | Low / high policy mix | Underwriting strategy | Advertising | Promotion |',
        '|---|---:|---:|---|---:|---:|---:|',
    ]
    for t in game['teams']:
        d = game['decisions'][str(t['id'])]['values']
        lines.append(f"| {t['name']} | {d['low_premium']:g} | {d['high_premium']:g} | "
                     f"{d['low_pct']:.0%} / {d['high_pct']:.0%} | {d['strategy']} | "
                     f"{d['advertising']:,.0f} | {d['promotion']:,.0f} |")
    lines += ['', 'All teams use zero screening, 10% reinsurance, 10% cash, 70% bonds, ',
              '20% stocks, Bond 1 (4%), and Stock 2 (100% of the 5% demo base return). ',
              'Each opens with 3,000,000 surplus, 1,000 policies, and 9,165,000 total assets.', '',
              '## Calculated results', '',
              '| Team | Market share | Policies | Gross premium | Closing surplus | Weighted surplus | Rank |',
              '|---|---:|---:|---:|---:|---:|---:|']
    for r in results:
        lines.append(f"| {r['name']} | {r['share']:.2%} | {r['policies']:,.2f} | {r['gross']:,.2f} | "
                     f"{r['score']:,.2f} | {r['cumulative']:,.2f} | {r['overall_rank']} |")
    lines += ['', 'Market share is measured by gross premium. Weighted surplus in this first round ',
              'is closing surplus multiplied by 16/127. Fractional policies are retained internally; ',
              'the browser rounds some displayed counts. Display rounding does not change rankings.', '',
              'The historical opening premium is 5 million per team, while the new demo quotes ',
              'are around 100 / 150. Opening reserves are retained, so first-round results include ',
              'the resulting reserve changes. See [RULES.md](../RULES.md) for the accounting formulas.', '',
              'The script creates and removes its own temporary database. It never opens `data/`, ',
              'and its output contains no classroom access codes, team passwords, or live data.', '']
    return '\n'.join(line.rstrip() for line in lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='Update docs/EXAMPLE_RESULTS.md')
    mode.add_argument('--check', action='store_true', help='Fail if the documented example is out of date')
    args = parser.parse_args()
    result = render_example()
    table = '\n'.join(line for line in result.split('## Calculated results\n', 1)[1].splitlines()
                      if line.startswith('|'))
    readme_path = ROOT / 'README.md'
    readme = readme_path.read_text(encoding='utf-8')
    start, end = '<!-- example-results:start -->', '<!-- example-results:end -->'
    if readme.count(start) != 1 or readme.count(end) != 1:
        parser.exit(1, 'README example markers are missing or duplicated.\n')
    before, rest = readme.split(start, 1)
    current_table, after = rest.split(end, 1)
    if args.check:
        if (not SNAPSHOT.exists() or SNAPSHOT.read_text(encoding='utf-8') != result
                or current_table.strip() != table):
            parser.exit(1, 'Example is out of date. Run python examples/demo_round.py --write\n')
        print('Documented example matches the current engine.')
    elif args.write:
        SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
        SNAPSHOT.write_text(result, encoding='utf-8', newline='\n')
        readme_path.write_text(before + start + '\n' + table + '\n' + end + after,
                               encoding='utf-8', newline='\n')
        print('Updated docs/EXAMPLE_RESULTS.md and the README example table.')
    else:
        print(result, end='')


if __name__ == '__main__':
    main()
